defmodule Backend.Accounts do
  @moduledoc """
  The Accounts context (ADR-007 #92 amendment): users with the roles `admin`
  and `student` (ADR-014 #346), sessions and login links, generated by
  `mix phx.gen.auth`. It calls no other context.
  """

  import Ecto.Query, warn: false
  alias Backend.Repo

  alias Backend.Accounts.{DeviceLogin, LegalDocuments, Scope, User, UserNotifier, UserToken}

  ## Database getters

  @doc """
  Gets a user by email.

  ## Examples

      iex> get_user_by_email("foo@example.com")
      %User{}

      iex> get_user_by_email("unknown@example.com")
      nil

  """
  def get_user_by_email(email) when is_binary(email) do
    Repo.get_by(User, email: email)
  end

  @doc """
  Gets a user by email and password.

  ## Examples

      iex> get_user_by_email_and_password("foo@example.com", "correct_password")
      %User{}

      iex> get_user_by_email_and_password("foo@example.com", "invalid_password")
      nil

  """
  def get_user_by_email_and_password(email, password)
      when is_binary(email) and is_binary(password) do
    user = Repo.get_by(User, email: email)
    if User.valid_password?(user, password), do: user
  end

  @doc """
  Gets a single user.

  Raises `Ecto.NoResultsError` if the User does not exist.

  ## Examples

      iex> get_user!(123)
      %User{}

      iex> get_user!(456)
      ** (Ecto.NoResultsError)

  """
  def get_user!(id), do: Repo.get!(User, id)

  ## User registration

  @doc """
  Registers a learner (#336): an unconfirmed `student` that accepted the
  current terms of use and privacy policy. The accepted versions and the
  acceptance time are stored; a role in `attrs` is ignored, so public sign-up
  never creates an admin.

  ## Examples

      iex> register_user(%{email: "a@b.c", terms_accepted: true, privacy_accepted: true})
      {:ok, %User{}}

      iex> register_user(%{email: "a@b.c"})
      {:error, %Ecto.Changeset{}}

  """
  @spec register_user(map()) :: {:ok, User.t()} | {:error, Ecto.Changeset.t()}
  def register_user(attrs) do
    %User{}
    |> User.registration_changeset(attrs, legal_versions())
    |> Repo.insert()
  end

  @doc """
  Returns an `%Ecto.Changeset{}` for the sign-up form. Takes the
  `:validate_unique` option of `Backend.Accounts.User.email_changeset/3`.
  """
  @spec change_user_registration(map(), keyword()) :: Ecto.Changeset.t()
  def change_user_registration(attrs \\ %{}, opts \\ []) do
    User.registration_changeset(%User{}, attrs, Keyword.merge(opts, legal_versions()))
  end

  @doc """
  Returns the current terms of use (`:terms`) or privacy policy (`:privacy`):
  title, version and paragraphs. The texts are placeholders (see
  `Backend.Accounts.LegalDocuments`).
  """
  @spec legal_document(LegalDocuments.kind()) :: LegalDocuments.t()
  def legal_document(kind), do: LegalDocuments.get(kind)

  defp legal_versions do
    [
      terms_version: LegalDocuments.get(:terms).version,
      privacy_version: LegalDocuments.get(:privacy).version
    ]
  end

  ## Settings

  @doc """
  Creates a confirmed admin with an email and a password.

  Only an operator calls it (`priv/repo/seeds.exs`); there is no public path
  that creates an admin.
  """
  @spec create_admin(map()) :: {:ok, User.t()} | {:error, Ecto.Changeset.t()}
  def create_admin(attrs) do
    attrs
    |> User.admin_changeset()
    |> Repo.insert()
  end

  @doc """
  Returns true when the scope belongs to an admin.
  """
  @spec admin?(Scope.t() | nil) :: boolean()
  def admin?(%Scope{user: %User{role: :admin}}), do: true
  def admin?(_scope), do: false

  @doc """
  Checks whether the user is in sudo mode.

  The user is in sudo mode when the last authentication was done no further
  than 20 minutes ago. The limit can be given as second argument in minutes.
  """
  def sudo_mode?(user, minutes \\ -20)

  def sudo_mode?(%User{authenticated_at: ts}, minutes) when is_struct(ts, DateTime) do
    DateTime.after?(ts, DateTime.utc_now() |> DateTime.add(minutes, :minute))
  end

  def sudo_mode?(_user, _minutes), do: false

  @doc """
  Returns an `%Ecto.Changeset{}` for changing the user email.

  See `Backend.Accounts.User.email_changeset/3` for a list of supported options.

  ## Examples

      iex> change_user_email(user)
      %Ecto.Changeset{data: %User{}}

  """
  def change_user_email(user, attrs \\ %{}, opts \\ []) do
    User.email_changeset(user, attrs, opts)
  end

  @doc """
  Updates the user email using the given token.

  If the token matches, the user email is updated and the token is deleted.
  """
  def update_user_email(user, token) do
    context = "change:#{user.email}"

    Repo.transact(fn ->
      with {:ok, query} <- UserToken.verify_change_email_token_query(token, context),
           %UserToken{sent_to: email} <- Repo.one(query),
           {:ok, user} <- Repo.update(User.email_changeset(user, %{email: email})),
           {_count, _result} <-
             Repo.delete_all(from(UserToken, where: [user_id: ^user.id, context: ^context])) do
        {:ok, user}
      else
        _ -> {:error, :transaction_aborted}
      end
    end)
  end

  @doc """
  Returns an `%Ecto.Changeset{}` for changing the user password.

  See `Backend.Accounts.User.password_changeset/3` for a list of supported options.

  ## Examples

      iex> change_user_password(user)
      %Ecto.Changeset{data: %User{}}

  """
  def change_user_password(user, attrs \\ %{}, opts \\ []) do
    User.password_changeset(user, attrs, opts)
  end

  @doc """
  Updates the user password.

  Returns a tuple with the updated user, as well as a list of expired tokens.

  ## Examples

      iex> update_user_password(user, %{password: ...})
      {:ok, {%User{}, [...]}}

      iex> update_user_password(user, %{password: "too short"})
      {:error, %Ecto.Changeset{}}

  """
  def update_user_password(user, attrs) do
    user
    |> User.password_changeset(attrs)
    |> update_user_and_delete_all_tokens()
  end

  ## Password reset (#336)

  @doc ~S"""
  Emails a password reset link to the user. The link is valid for 24 hours and
  only while the user's email is unchanged.

  ## Examples

      iex> deliver_user_reset_password_instructions(user, &url(~p"/users/reset-password/#{&1}"))
      {:ok, %Swoosh.Email{}}

  """
  def deliver_user_reset_password_instructions(%User{} = user, reset_password_url_fun)
      when is_function(reset_password_url_fun, 1) do
    {encoded_token, user_token} = UserToken.build_email_token(user, "reset_password")
    Repo.insert!(user_token)
    UserNotifier.deliver_reset_password_instructions(user, reset_password_url_fun.(encoded_token))
  end

  @doc """
  Gets the user of a valid password reset token, or `nil`.
  """
  @spec get_user_by_reset_password_token(String.t()) :: User.t() | nil
  def get_user_by_reset_password_token(token) when is_binary(token) do
    with {:ok, query} <- UserToken.verify_reset_password_token_query(token),
         %User{} = user <- Repo.one(query) do
      user
    else
      _ -> nil
    end
  end

  @doc """
  Sets a new password from a reset link and expires all the user's tokens.

  The link proved the user owns the email, so an unconfirmed account is
  confirmed too. Returns the user and the expired tokens, so the caller can
  disconnect their sessions.
  """
  @spec reset_user_password(User.t(), map()) ::
          {:ok, {User.t(), [UserToken.t()]}} | {:error, Ecto.Changeset.t()}
  def reset_user_password(%User{} = user, attrs) do
    user
    |> User.password_changeset(attrs)
    |> confirm_if_unconfirmed()
    |> update_user_and_delete_all_tokens()
  end

  defp confirm_if_unconfirmed(%Ecto.Changeset{data: %User{confirmed_at: nil}} = changeset),
    do: Ecto.Changeset.put_change(changeset, :confirmed_at, DateTime.utc_now(:second))

  defp confirm_if_unconfirmed(changeset), do: changeset

  ## Account deletion (#336)

  @doc """
  Deletes a learner account and all its data, returning the tokens whose
  sessions the caller disconnects. Admin accounts are never deleted here.

  The deletion hook for the other contexts is the database: every table that
  holds a user's data references `users` with `on_delete: :delete_all`, so this
  single `DELETE` erases it in the same transaction (results #338, billing
  #339). `Backend.Accounts.AccountDeletionTest` fails for any foreign key to
  `users` that does not cascade, unless it lists the reference as admin-only. Data kept outside Postgres needs its own
  cleanup, added with the context that introduces it.
  """
  @spec delete_user(User.t()) :: {:ok, [UserToken.t()]} | {:error, :admin_account}
  def delete_user(%User{role: :admin}), do: {:error, :admin_account}

  def delete_user(%User{} = user) do
    Repo.transact(fn ->
      tokens = Repo.all_by(UserToken, user_id: user.id)
      Repo.delete!(user)
      {:ok, tokens}
    end)
  end

  @doc """
  Returns true when the typed email confirms deleting the user's account
  (case and surrounding whitespace are ignored).
  """
  @spec account_deletion_confirmed?(User.t(), term()) :: boolean()
  def account_deletion_confirmed?(%User{email: email}, typed_email) when is_binary(typed_email) do
    String.downcase(String.trim(typed_email)) == String.downcase(email)
  end

  def account_deletion_confirmed?(_user, _typed_email), do: false

  ## Session

  @doc """
  Generates a session token.
  """
  def generate_user_session_token(user) do
    {token, user_token} = UserToken.build_session_token(user)
    Repo.insert!(user_token)
    token
  end

  @doc """
  Gets the user with the given signed token.

  If the token is valid `{user, token_inserted_at}` is returned, otherwise `nil` is returned.
  """
  def get_user_by_session_token(token) do
    {:ok, query} = UserToken.verify_session_token_query(token)
    Repo.one(query)
  end

  @doc """
  Gets the user with the given magic link token.
  """
  def get_user_by_magic_link_token(token) do
    with {:ok, query} <- UserToken.verify_magic_link_token_query(token),
         {user, _token} <- Repo.one(query) do
      user
    else
      _ -> nil
    end
  end

  @doc """
  Logs the user in by magic link.

  There are three cases to consider:

  1. The user has already confirmed their email. They are logged in
     and the magic link is expired.

  2. The user has not confirmed their email and no password is set.
     In this case, the user gets confirmed, logged in, and all tokens -
     including session ones - are expired. In theory, no other tokens
     exist but we delete all of them for best security practices.

  3. The user has not confirmed their email but a password is set.
     This cannot happen in the default implementation but may be the
     source of security pitfalls. See the "Mixing magic link and password registration" section of
     `mix help phx.gen.auth`.
  """
  def login_user_by_magic_link(token) do
    {:ok, query} = UserToken.verify_magic_link_token_query(token)

    case Repo.one(query) do
      # Prevent session fixation attacks by disallowing magic links for unconfirmed users with password
      {%User{confirmed_at: nil, hashed_password: hash}, _token} when not is_nil(hash) ->
        raise """
        magic link log in is not allowed for unconfirmed users with a password set!

        This cannot happen with the default implementation, which indicates that you
        might have adapted the code to a different use case. Please make sure to read the
        "Mixing magic link and password registration" section of `mix help phx.gen.auth`.
        """

      {%User{confirmed_at: nil} = user, _token} ->
        user
        |> User.confirm_changeset()
        |> update_user_and_delete_all_tokens()

      {user, token} ->
        Repo.delete!(token)
        {:ok, {user, []}}

      nil ->
        {:error, :not_found}
    end
  end

  @doc ~S"""
  Delivers the update email instructions to the given user.

  ## Examples

      iex> deliver_user_update_email_instructions(user, current_email, &url(~p"/users/settings/confirm-email/#{&1}"))
      {:ok, %{to: ..., body: ...}}

  """
  def deliver_user_update_email_instructions(%User{} = user, current_email, update_email_url_fun)
      when is_function(update_email_url_fun, 1) do
    {encoded_token, user_token} = UserToken.build_email_token(user, "change:#{current_email}")

    Repo.insert!(user_token)
    UserNotifier.deliver_update_email_instructions(user, update_email_url_fun.(encoded_token))
  end

  @doc """
  Delivers the magic link login instructions to the given user.
  """
  def deliver_login_instructions(%User{} = user, magic_link_url_fun)
      when is_function(magic_link_url_fun, 1) do
    {encoded_token, user_token} = UserToken.build_email_token(user, "login")
    Repo.insert!(user_token)
    UserNotifier.deliver_login_instructions(user, magic_link_url_fun.(encoded_token))
  end

  @doc """
  Deletes the signed token with the given context.
  """
  def delete_user_session_token(token) do
    Repo.delete_all(from(UserToken, where: [token: ^token, context: "session"]))
    :ok
  end

  ## Device login (#337)

  @doc """
  Starts a device login for the Unreal client (RFC 8628 shape). Returns the
  secret `device_code` the client polls with, the `user_code` (`XXXX-XXXX`)
  the learner confirms in the browser, the polling `interval` and the
  lifetime `expires_in`, both in seconds. Only hashes are stored.
  """
  @spec start_device_authorization() :: {:ok, DeviceLogin.start()}
  defdelegate start_device_authorization, to: DeviceLogin, as: :start

  @doc """
  Returns true when the user code (any case, dash optional) names a pending,
  unexpired device login.
  """
  @spec pending_device_authorization?(term()) :: boolean()
  defdelegate pending_device_authorization?(user_code), to: DeviceLogin, as: :pending?

  @doc """
  The learner approves the device login of `user_code`; the client's next
  poll receives the tokens. Admin accounts may not use the device flow.
  """
  @spec approve_device_authorization(User.t(), term()) ::
          :ok | {:error, :invalid_code | :admin_account}
  def approve_device_authorization(%User{} = user, user_code),
    do: DeviceLogin.decide(user, user_code, :approved)

  @doc """
  The learner denies the device login of `user_code`; the client's next poll
  receives `access_denied`.
  """
  @spec deny_device_authorization(User.t(), term()) :: :ok | {:error, :invalid_code}
  def deny_device_authorization(%User{} = user, user_code),
    do: DeviceLogin.decide(user, user_code, :denied)

  @doc """
  Polls a device login with its `device_code`. Returns the tokens once after
  approval, or one of the RFC 8628 errors `:authorization_pending`,
  `:slow_down` (the interval grows by 5 seconds), `:expired_token`,
  `:access_denied`, or `:invalid_grant` for an unknown or consumed code.
  """
  @spec poll_device_authorization(term()) ::
          {:ok, DeviceLogin.tokens()} | {:error, DeviceLogin.poll_error()}
  defdelegate poll_device_authorization(device_code), to: DeviceLogin, as: :poll

  @doc """
  Exchanges a refresh token for a new access and refresh token pair. The old
  pair stops working; presenting the old refresh token again revokes the
  whole device login.
  """
  @spec refresh_device_token(term()) :: {:ok, DeviceLogin.tokens()} | {:error, :invalid_grant}
  defdelegate refresh_device_token(refresh_token), to: DeviceLogin, as: :refresh

  @doc """
  Gets the user of a valid, unexpired device access token, or `nil`.
  """
  @spec get_user_by_device_access_token(term()) :: User.t() | nil
  defdelegate get_user_by_device_access_token(token), to: DeviceLogin, as: :user_by_access_token

  @doc """
  Logs out the device login of this access token (its refresh token too).
  """
  @spec revoke_device_token(term()) :: :ok
  defdelegate revoke_device_token(access_token), to: DeviceLogin, as: :revoke

  @doc """
  Logs the user out of every device. Changing or resetting the password does
  the same, and deleting the account erases the tokens with it.
  """
  @spec revoke_all_device_tokens(User.t()) :: :ok
  def revoke_all_device_tokens(%User{} = user), do: DeviceLogin.revoke_all(user)

  ## Token helper

  # Also revokes every device login (#337): a password change logs the
  # learner out of the Unreal client too.
  defp update_user_and_delete_all_tokens(changeset) do
    Repo.transact(fn ->
      with {:ok, user} <- Repo.update(changeset) do
        tokens_to_expire = Repo.all_by(UserToken, user_id: user.id)

        Repo.delete_all(from(t in UserToken, where: t.id in ^Enum.map(tokens_to_expire, & &1.id)))
        :ok = DeviceLogin.revoke_all(user)

        {:ok, {user, tokens_to_expire}}
      end
    end)
  end
end
